"""Generates the synthetic training dataset for the architecture classifier.

Labels are the argmax of a weighted utility score over the eleven pre-build
features (each architecture style gets a score; the highest wins), plus a small
amount of Gaussian noise so the boundaries stay realistic rather than perfectly
separable. The previous version sampled the label from a softmax with heavy
noise, which meant ~37% of labels contradicted the features -- pure label noise
that capped a perfectly trained model at ~63% accuracy. The label is now
consistent with the features, which is what the classifier can actually learn.

Rows are generated by rejection sampling so the three classes are equally
represented; a skewed dataset was the second reason Monolith and Serverless were
rarely predicted correctly.
"""
import csv
import random
from pathlib import Path

BUDGETS = ["low", "medium", "high"]
USER_SCALES = ["low", "medium", "high"]
DATA_COMPLEXITY = ["low", "medium", "high"]
AVAILABILITY = ["low", "medium", "high"]
DOMAINS = [
    "food_delivery", "e_commerce", "social_media", "fintech", "healthtech",
    "edtech", "logistics", "gaming", "media_streaming", "productivity_tool",
    "iot_platform", "booking_platform", "marketplace", "analytics_dashboard",
    "content_management",
]

ORDINAL = {"low": 0, "medium": 1, "high": 2}

ARCHITECTURES = ["Monolith", "Microservices", "Serverless"]

ROWS_PER_CLASS = 400
LABEL_NOISE = 0.12


def sample_row(rng):
    return {
        "team_size": rng.choice([1, 2, 3, 4, 5, 6, 7, 8, 10, 12, 15, 20]),
        "budget": rng.choice(BUDGETS),
        "expected_users": rng.choice(USER_SCALES),
        "number_of_roles": rng.randint(1, 6),
        "number_of_modules": rng.randint(1, 12),
        "real_time": rng.random() < 0.35,
        "payment": rng.random() < 0.45,
        "external_integrations": rng.randint(0, 6),
        "data_complexity": rng.choice(DATA_COMPLEXITY),
        "availability": rng.choice(AVAILABILITY),
        "domain": rng.choice(DOMAINS),
    }


def score_row(row):
    """Utility score per architecture style for one row.

    Scores combine several interacting signals instead of a single cutoff:
    a large team with high traffic, many modules, many integrations and high
    availability leans microservices; a tiny team building a single-purpose
    service on a low budget leans serverless; everything in between leans
    monolith.
    """
    team = row["team_size"]
    budget = ORDINAL[row["budget"]]
    users = ORDINAL[row["expected_users"]]
    modules = row["number_of_modules"]
    roles = row["number_of_roles"]
    integrations = row["external_integrations"]
    complexity = ORDINAL[row["data_complexity"]]
    availability = ORDINAL[row["availability"]]
    real_time = 1.0 if row["real_time"] else 0.0
    payment = 1.0 if row["payment"] else 0.0

    microservices = (
        1.2 * users
        + 1.2 * availability
        + 0.7 * complexity
        + 0.5 * (min(team, 15) / 15) * 3
        + 0.5 * (min(modules, 15) / 15) * 2.5
        + 0.4 * (integrations / 6) * 2
        + 0.25 * payment
        + 0.2 * real_time
        - 0.7 * (2 - budget)
        - (0.7 if team <= 2 else 0.0)
        - (0.3 if modules <= 3 else 0.0)
    )

    serverless = (
        1.4 * (1.0 if modules <= 3 else 0.15)
        + 1.0 * (1.0 if roles <= 2 else 0.1)
        + 0.9 * (1.0 if team <= 2 else 0.2)
        + 0.7 * (2 - budget)
        + 0.2 * (2 - availability)
        + 0.25 * real_time
        + 0.1 * payment
        - 0.5 * users
        - 0.4 * complexity
        - 0.35 * (1.0 if availability == 2 else 0.0)
    )

    monolith = (
        1.0
        + 1.0 * (1.0 if modules <= 7 else 0.1)
        + 0.5 * (1 - min(team, 10) / 10)
        + 0.24 * (2 - availability)
        + 0.3 * (2 - complexity)
        + 0.2 * (2 - budget)
        - 0.6 * users
        - (0.5 if team >= 8 else 0.0)
        - 0.4 * real_time
        - 0.3 * integrations / 6
    )

    return {
        "Microservices": microservices,
        "Serverless": serverless,
        "Monolith": monolith,
    }


def label_row(row, rng):
    scores = {
        name: value + rng.gauss(0, LABEL_NOISE)
        for name, value in score_row(row).items()
    }
    return max(scores, key=scores.get)


def generate(rows_per_class=ROWS_PER_CLASS, seed=42):
    rng = random.Random(seed)
    rows = []
    counts = {name: 0 for name in ARCHITECTURES}
    attempts = 0
    max_attempts = rows_per_class * len(ARCHITECTURES) * 100

    while min(counts.values()) < rows_per_class and attempts < max_attempts:
        attempts += 1
        row = sample_row(rng)
        label = label_row(row, rng)
        if counts[label] >= rows_per_class:
            continue
        row["architecture"] = label
        rows.append(row)
        counts[label] += 1

    rng.shuffle(rows)
    return rows


def main():
    rows = generate()
    out_path = Path(__file__).parent / "synthetic_dataset.csv"
    fieldnames = list(rows[0].keys())
    with out_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    counts = {}
    for row in rows:
        counts[row["architecture"]] = counts.get(row["architecture"], 0) + 1
    print(f"Wrote {len(rows)} rows to {out_path}")
    print(f"Class distribution: {counts}")


if __name__ == "__main__":
    main()
